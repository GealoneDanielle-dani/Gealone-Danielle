public class DataTypeShowcase { 
   public static void main(String[] args) {
    byte age = 23;
    int studentID = 2010426;
    long population = 110000000L;
   float gwa = 1.75f;
    double pi = 3.14159;
    char grade = 'A';
    boolean passed = true;

    System.out.println("byte: " + age);
   System.out.println("int: " + studentID);
    System.out.println("long:" + population);
   System.out.println("float: " + gwa);
    System.out.println("double: " + pi);
    System.out.println("char: " + grade);
    System.out.println("boolean: " + passed);

   }
    
}
